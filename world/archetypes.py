_BY_ID = {archetype["id"]: archetype for archetype in ARCHETYPES}


def get_archetype(archetype_id):
    return _BY_ID.get(archetype_id, ARCHETYPES[0])


def pick_archetype(rng: random.Random):
    total = sum(archetype["weight"] for archetype in ARCHETYPES)
    roll = rng.random() * total
    for archetype in ARCHETYPES:
        roll -= archetype["weight"]
        if roll <= 0.0:
            return archetype
    return ARCHETYPES[-1]
